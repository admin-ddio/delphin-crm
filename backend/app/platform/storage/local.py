"""Local-disk StorageBackend: files under settings.storage_dir, keyed by opaque ids.

Keys are generated by the caller (never user-supplied file names), are validated
here, and are sharded by prefix so no directory grows unbounded. Production can swap
in an S3-compatible backend behind the same protocol.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import AsyncIterator
from functools import lru_cache
from pathlib import Path
from typing import Annotated

import anyio
from fastapi import Depends

from app.core.config import Settings, get_app_settings
from app.platform.storage.interfaces import StorageBackend, StoredObject

_KEY = re.compile(r"^[a-z0-9][a-z0-9/_-]{2,200}$")
CHUNK = 64 * 1024


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self._root = Path(root)

    def _path(self, key: str) -> Path:
        if not _KEY.fullmatch(key) or ".." in key:
            msg = f"Invalid storage key: {key!r}"
            raise ValueError(msg)
        return self._root / key

    async def put(self, key: str, data: bytes, *, content_type: str) -> StoredObject:
        path = self._path(key)
        await anyio.Path(path.parent).mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".part")
        await anyio.Path(tmp).write_bytes(data)
        await anyio.Path(tmp).rename(path)
        return StoredObject(
            key=key,
            size=len(data),
            sha256=hashlib.sha256(data).hexdigest(),
            content_type=content_type,
        )

    async def open(self, key: str) -> AsyncIterator[bytes]:
        async with await anyio.open_file(self._path(key), "rb") as handle:
            while chunk := await handle.read(CHUNK):
                yield chunk

    async def delete(self, key: str) -> None:
        path = anyio.Path(self._path(key))
        if await path.exists():
            await path.unlink()

    async def exists(self, key: str) -> bool:
        return await anyio.Path(self._path(key)).exists()


@lru_cache
def _storage(root: str) -> LocalStorage:
    return LocalStorage(root)


def get_storage(settings: Annotated[Settings, Depends(get_app_settings)]) -> StorageBackend:
    return _storage(settings.storage_dir)
